-- Blackthornes Farmer -- Locale/zhCN.lua
-- Simplified Chinese: the words players see, on a Simplified Chinese client.
--
-- Each line is the English key (exactly as the code writes it) and its
-- Chinese. A key with no line here shows in English. The Chinese uses the
-- game's own words (拾取, 战利品, 目标, 怪物, 资源点, 采矿, 草药学, 剥皮,
-- 钓鱼, 鱼群, 商人, 拍卖行, 等级, 区域, 码). A line may name its values by
-- place ("%2$s ... %1$s") where Chinese word order needs it; L.Format puts
-- them in order.
--
-- Item, mob, zone and skill names stay as the data or the client gives
-- them. tools/check_locale.py lists keys with no line here and lines no
-- longer used.

