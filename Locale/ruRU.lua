-- Blackthornes Farmer -- Locale/ruRU.lua
-- Русский (Russian): the words players see, on a Russian client.
--
-- Each line is the English key (exactly as the code writes it) and its
-- Russian. A key with no line here shows in English. The Russian speaks to
-- the player as "ты", in a friendly voice, and uses the game's words
-- (добыча, цель, противник, рудная жила, травы, горное дело, травничество,
-- снятие шкур, рыбная ловля, косяк рыбы, торговец, аукцион, уровень, зона,
-- метры). A line may name its values by place ("%2$s ... %1$s") where
-- Russian word order needs it; L.Format puts them in order. Russian has
-- three plural forms; where the code picks between two keys, the second
-- is the form that reads best after most numbers.
--
-- Item, mob, zone and skill names stay as the data or the client gives
-- them. tools/check_locale.py lists keys with no line here and lines no
-- longer used.

