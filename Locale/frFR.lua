-- Blackthornes Farmer -- Locale/frFR.lua
-- Français (French): the words players see, on a French client.
--
-- Each line is the English key (exactly as the code writes it) and its
-- French. A key with no line here shows in English. The French speaks to
-- the player as "tu", in a friendly voice, and uses the game's words
-- (butin, objectif, monstre, gisement, filon, herbe, minage, herboristerie,
-- dépeçage, pêche, banc de poissons, marchand, hôtel des ventes, niveau,
-- zone, mètres). A line may name its values by place ("%2$s ... %1$s")
-- where French word order needs it; L.Format puts them in order.
--
-- Item, mob, zone and skill names stay as the data or the client gives
-- them. tools/check_locale.py lists keys with no line here and lines no
-- longer used.

local _, ns = ...
local L = ns.L

local ok, locale = pcall(function() return GetLocale() end)
if not (ok and locale == "frFR") then return end

