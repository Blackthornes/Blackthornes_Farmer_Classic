"""Writes Data/NodeSpots.lua: where Classic's herbs and ore veins grow.

Run from the repository root with pfQuest checked out somewhere:

    python tools/make_node_spots.py <pfQuest>

  github.com/shagu/pfQuest   db/meta.lua (which objects are herbs and
                             veins), db/objects.lua (their spawn spots),
                             db/<locale>/objects.lua (their names),
                             db/enUS/zones.lua (zone names)

The arrow by your feet on Era (UI/NodeSparkle.lua) points at the node you
face. The client never says where a node is, so the arrow looks for the
nearest spot you gathered that node at, else the nearest spot in this file.

    ns.NODE_SPOTS[mapID][English name] = "xxxyyyxxxyyy..."

Each spot is six digits, x and y in tenths of a percent of the zone's map
(0 to 999), the map ID the one Data/Zones.lua gives the zone. A zone whose
map is not known is left out.

    ns.NODE_NAMES[locale][client's name] = English name

so a German client's "Friedensblume" finds Peacebloom's spots. "esES" covers
both Spanish clients.

Never edit the output by hand; rerun this.
"""

import re
import sys
from pathlib import Path

OUT = Path("Data/NodeSpots.lua")
ZONES = Path("Data/Zones.lua")
LOCALES = ["deDE", "frFR", "esES", "ruRU", "zhCN"]


def category(meta, name):
    start = meta.index('["%s"] = {' % name)
    end = meta.index("\n  },", start)
    return [int(oid) for oid in re.findall(r"\[-(\d+)\] = \d+", meta[start:end])]


def names(path):
    text = path.read_text(encoding="utf-8")
    found = re.findall(r'\[(\d+)\] = "((?:[^"\\]|\\.)*)"', text)
    return dict((int(oid), re.sub(r"\\(.)", r"\1", name)) for oid, name in found)


def spots(objects, oid):
    start = objects.find("\n  [%d] = {" % oid)
    if start < 0:
        return []
    end = objects.find("\n  },", start)
    found = re.findall(r"\{ ([\d.]+), ([\d.]+), (\d+), \d+ \}", objects[start:end])
    return [(float(x), float(y), int(zone)) for x, y, zone in found]


def lua(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    db = Path(sys.argv[1]) / "db"

    meta = (db / "meta.lua").read_text(encoding="utf-8")
    nodes = category(meta, "herbs") + category(meta, "mines")
    objects = (db / "objects.lua").read_text(encoding="utf-8")
    english = names(db / "enUS" / "objects.lua")
    zones = names(db / "enUS" / "zones.lua")
    maps = dict((name, int(mid)) for name, mid in
                re.findall(r'\["([^"]+)"\] = (\d+),', ZONES.read_text(encoding="utf-8").split("names = {")[0]))

    table = {}
    missing = set()
    for oid in sorted(nodes):
        name = english.get(oid)
        if not name:
            continue
        for x, y, zone in spots(objects, oid):
            mid = maps.get(zones.get(zone))
            if not mid:
                missing.add(zones.get(zone, zone))
                continue
            key = (min(999, round(x * 10)), min(999, round(y * 10)))
            table.setdefault(mid, {}).setdefault(name, set()).add(key)

    local = {}
    for locale in LOCALES:
        path = db / locale / "objects.lua"
        if not path.exists():
            continue
        theirs = names(path)
        for oid in nodes:
            if oid in english and theirs.get(oid) and theirs[oid] != english[oid]:
                local.setdefault(locale, {})[theirs[oid]] = english[oid]

    count = sum(len(s) for zone in table.values() for s in zone.values())
    lines = [
        "-- Blackthornes Farmer -- Data/NodeSpots.lua",
        "-- Generated by tools/make_node_spots.py; never edit by hand.",
        "-- Where Classic's herbs and ore veins grow, for the arrow by your feet.",
        "",
        "local _, ns = ...",
        "",
        "ns.NODE_SPOTS = {",
    ]
    for mid in sorted(table):
        lines.append("    [%d] = {" % mid)
        for name in sorted(table[mid]):
            packed = "".join("%03d%03d" % spot for spot in sorted(table[mid][name]))
            lines.append("        [%s] = \"%s\"," % (lua(name), packed))
        lines.append("    },")
    lines.append("}")
    lines.append("")
    lines.append("ns.NODE_NAMES = {")
    for locale in sorted(local):
        lines.append("    %s = {" % locale)
        for name in sorted(local[locale]):
            lines.append("        [%s] = %s," % (lua(name), lua(local[locale][name])))
        lines.append("    },")
    lines.append("}")
    lines.append("ns.NODE_NAMES.esMX = ns.NODE_NAMES.esES")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote %s: %d spots in %d zones" % (OUT, count, len(table)))
    if missing:
        print("left out, no map: %s" % ", ".join(sorted(str(m) for m in missing)))


if __name__ == "__main__":
    main()
